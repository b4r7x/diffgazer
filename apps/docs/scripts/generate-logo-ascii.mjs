import { mkdir, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import figlet from "figlet";

const DOCS_ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const OUTPUT_PATH = resolve(DOCS_ROOT, "src/generated/logo-ascii.ts");

// The docs hero wordmark. The same art is hardcoded in apps/web
// (src/components/layout/wordmark.tsx) and in the landing hero and HUD: those
// surfaces cannot import from each other, and a shared home would mean promoting
// the art into libs/core, so the copies are deliberate. Font, casing, and
// trailing-blank-row trim must be kept in sync by hand if any side changes;
// scripts/monorepo/wordmark-parity.test.mjs is the gate that enforces it.
const WORDMARK_TEXT = "diffgazer";
const WORDMARK_FONT = "Big";

function trimTrailingBlankRows(ascii) {
  const rows = ascii.split("\n");
  while (rows.length > 0 && rows[rows.length - 1].trim() === "") rows.pop();
  return rows.join("\n");
}

const wordmark = trimTrailingBlankRows(
  figlet.textSync(WORDMARK_TEXT.toUpperCase(), { font: WORDMARK_FONT }),
);

// The art's own grid, emitted so chrome that has to reserve space for the block
// can derive it (rows -> em, cols -> ch at the layout font size) instead of
// hardcoding a measurement that silently rots when the art changes.
const rows = wordmark.split("\n");
const WORDMARK_ROWS = rows.length;
const WORDMARK_COLS = Math.max(...rows.map((row) => row.length));

const contents = `// Generated by apps/docs/scripts/generate-logo-ascii.mjs. Do not edit.\nexport const WORDMARK_TEXT = ${JSON.stringify(WORDMARK_TEXT)};\n\nexport const WORDMARK_ASCII = ${JSON.stringify(wordmark)};\n\nexport const WORDMARK_ROWS = ${WORDMARK_ROWS};\n\nexport const WORDMARK_COLS = ${WORDMARK_COLS};\n`;

await mkdir(dirname(OUTPUT_PATH), { recursive: true });
await writeFile(OUTPUT_PATH, contents, "utf8");

console.log(`[logo-ascii] wrote the ${WORDMARK_TEXT} wordmark to ${OUTPUT_PATH}`);
